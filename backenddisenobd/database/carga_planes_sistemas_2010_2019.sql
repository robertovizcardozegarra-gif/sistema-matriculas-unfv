USE sistema_matriculas_unfv;

CREATE TABLE IF NOT EXISTS GrupoElectivo (
  CodFac               INT NOT NULL,
  CodEsc               INT NOT NULL,
  CorrPE               INT NOT NULL,
  CodGrupo             VARCHAR(20) NOT NULL,
  DenGrupo             VARCHAR(150) NOT NULL,
  Semestre             TINYINT NOT NULL,
  CantidadRequerida    TINYINT NOT NULL DEFAULT 1,
  CreditosComputables  DECIMAL(4,1) NOT NULL,
  Estado               CHAR(1) NOT NULL DEFAULT 'A',
  PRIMARY KEY (CodFac, CodEsc, CorrPE, CodGrupo),
  CONSTRAINT fk_grupo_electivo_plan FOREIGN KEY (CodFac, CodEsc, CorrPE)
    REFERENCES PlanEstudio (CodFac, CodEsc, CorrPE),
  CONSTRAINT chk_grupo_electivo_semestre CHECK (Semestre BETWEEN 1 AND 10),
  CONSTRAINT chk_grupo_electivo_cantidad CHECK (CantidadRequerida > 0),
  CONSTRAINT chk_grupo_electivo_creditos CHECK (CreditosComputables > 0),
  CONSTRAINT chk_grupo_electivo_estado CHECK (Estado IN ('A', 'I'))
) ENGINE=InnoDB;

SET @columna_grupo_existe = (
  SELECT COUNT(*)
  FROM information_schema.COLUMNS
  WHERE TABLE_SCHEMA = DATABASE()
    AND TABLE_NAME = 'Curso'
    AND COLUMN_NAME = 'CodGrupoElectivo'
);
SET @ddl_columna_grupo = IF(
  @columna_grupo_existe = 0,
  'ALTER TABLE Curso ADD COLUMN CodGrupoElectivo VARCHAR(20) NULL AFTER TipoCurso',
  'SELECT 1'
);
PREPARE stmt_columna_grupo FROM @ddl_columna_grupo;
EXECUTE stmt_columna_grupo;
DEALLOCATE PREPARE stmt_columna_grupo;

SET @indice_grupo_existe = (
  SELECT COUNT(*)
  FROM information_schema.STATISTICS
  WHERE TABLE_SCHEMA = DATABASE()
    AND TABLE_NAME = 'Curso'
    AND INDEX_NAME = 'idx_curso_grupo_electivo'
);
SET @ddl_indice_grupo = IF(
  @indice_grupo_existe = 0,
  'ALTER TABLE Curso ADD KEY idx_curso_grupo_electivo (CodFac, CodEsc, CorrPE, CodGrupoElectivo)',
  'SELECT 1'
);
PREPARE stmt_indice_grupo FROM @ddl_indice_grupo;
EXECUTE stmt_indice_grupo;
DEALLOCATE PREPARE stmt_indice_grupo;

SET @fk_grupo_existe = (
  SELECT COUNT(*)
  FROM information_schema.TABLE_CONSTRAINTS
  WHERE CONSTRAINT_SCHEMA = DATABASE()
    AND TABLE_NAME = 'Curso'
    AND CONSTRAINT_NAME = 'fk_curso_grupo_electivo'
);
SET @ddl_fk_grupo = IF(
  @fk_grupo_existe = 0,
  'ALTER TABLE Curso ADD CONSTRAINT fk_curso_grupo_electivo FOREIGN KEY (CodFac, CodEsc, CorrPE, CodGrupoElectivo) REFERENCES GrupoElectivo (CodFac, CodEsc, CorrPE, CodGrupo)',
  'SELECT 1'
);
PREPARE stmt_fk_grupo FROM @ddl_fk_grupo;
EXECUTE stmt_fk_grupo;
DEALLOCATE PREPARE stmt_fk_grupo;

